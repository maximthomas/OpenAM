/**
 * Backend coverage reporter (design.md D16).
 *
 * D16 asks that a run declare which backends it exercised, and that a spec it did not run be
 * "reported as not run rather than as passed". The failure that guards against is a suite which
 * quietly shrinks: `--grep @local-server` drops 10 of the 15 spec files at collection time, and
 * Playwright's own summary for that run — a green "23 passed" — is the same shape as the summary
 * for the full one. Nothing in the output says the other 10 never ran.
 *
 * So this reporter prints a coverage block after the run: how many spec files exist on disk, which
 * of them ran, which did not and why, and any that declare no backend tag at all. It is additive
 * and never changes the exit status — an undeclared spec is loud, not blocking. That is the
 * requirement's literal reading ("reported as not run"), and it keeps the tag parser below off the
 * critical path: a tag written in a form the parser misses produces a wrong line in a report
 * rather than a red build.
 *
 * Two sources of truth for a file's tags, deliberately:
 *   - a file that ran contributes Playwright's own `TestCase.tags` — authoritative;
 *   - a file that did not run contributes a static parse, since its tags were never evaluated.
 * Where both are available they are compared, and a disagreement is printed. That is the parser's
 * self-check: it is exercised against the authoritative answer on every full run.
 */

import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

/** The tags D16 defines. A spec declaring none of these is undeclared, whatever else it carries. */
const BACKEND_TAGS = ["@deployed-am", "@local-server"];

/** Mirrors `testMatch` in playwright.config.mjs. */
const SPEC_SUFFIX = ".spec.mjs";

/**
 * Directories a spec file never lives in. Deliberately short: a directory skipped here is a
 * directory whose specs this report would not know about, which is the failure D16 is about. These
 * four are vendored or generated by the run itself, so none can hold a source spec.
 */
const SKIP_DIRS = new Set(["node_modules", "test-results", "playwright-report", ".git"]);

/** Every spec file on disk under `root`, as absolute paths. */
function findSpecFiles(root) {
    const out = [];
    const walk = (dir) => {
        let entries;
        try {
            entries = readdirSync(dir, { withFileTypes: true });
        } catch {
            return;
        }
        for (const entry of entries) {
            const full = join(dir, entry.name);
            if (entry.isDirectory()) {
                if (!SKIP_DIRS.has(entry.name)) walk(full);
            } else if (entry.name.endsWith(SPEC_SUFFIX)) {
                out.push(full);
            }
        }
    };
    if (statSync(root, { throwIfNoEntry: false })) walk(root);
    return out.sort();
}

/**
 * The backend tags a spec file declares, read statically.
 *
 * Comments are stripped first, because two specs carry prose saying they are *deliberately not*
 * tagged `@local-server` (xui-auth-modules, xui-auth-chains) — a parser that read comments would
 * report the opposite of what they declare. Block comments go entirely; line comments only when
 * they start a line, so that URLs inside string literals survive.
 */
function parseDeclaredTags(source) {
    const code = source
        .replace(/\/\*[\s\S]*?\*\//g, " ")
        .replace(/^[ \t]*\/\/.*$/gm, " ");
    const found = new Set();
    for (const match of code.matchAll(/\btag\s*:\s*(\[[^\]]*\]|"[^"]*"|'[^']*'|`[^`]*`)/g)) {
        for (const tag of match[1].matchAll(/@[\w-]+/g)) {
            if (BACKEND_TAGS.includes(tag[0])) found.add(tag[0]);
        }
    }
    return found;
}

/** `config.grep` is a RegExp or an array of them; the default matches everything. */
function grepPatterns(grep) {
    const list = Array.isArray(grep) ? grep : grep ? [grep] : [];
    return list.filter((re) => re.source !== ".*");
}

/**
 * The tag filter, read from the command line.
 *
 * `--grep` given on the CLI never reaches a reporter: Playwright applies it as a filtering layer of
 * its own and leaves `FullConfig.grep` at its match-everything default, so a run filtered down to
 * five spec files looks, from in here, exactly like an unfiltered one. Verified on Playwright 1.60.
 * `process.argv` is the only place the reporter can see it — reporters run in the main process, so
 * the invocation is right there. A grep set in the config file still comes through `config.grep`,
 * so both are read and the CLI wins, matching Playwright's own precedence.
 */
function readGrepArgs(argv) {
    const grep = [];
    const invert = [];
    for (let i = 0; i < argv.length; i += 1) {
        const arg = argv[i];
        let target = null;
        let value;
        if (arg === "--grep" || arg === "-g") {
            target = grep;
            value = argv[i + 1];
            i += 1;
        } else if (arg.startsWith("--grep=")) {
            target = grep;
            value = arg.slice("--grep=".length);
        } else if (arg === "--grep-invert") {
            target = invert;
            value = argv[i + 1];
            i += 1;
        } else if (arg.startsWith("--grep-invert=")) {
            target = invert;
            value = arg.slice("--grep-invert=".length);
        }
        if (target && value !== undefined) target.push(value);
    }
    return { grep, invert };
}

/** A pattern given as a string on the CLI is a regex to Playwright, and is matched as one here. */
function matchesAny(patterns, tags) {
    return patterns.some((pattern) => {
        let re;
        try {
            re = new RegExp(pattern);
        } catch {
            return false;
        }
        return [...tags].some((tag) => re.test(tag));
    });
}

const sorted = (tags) => [...tags].sort().join(" ");

class BackendTagReporter {
    onBegin(config, suite) {
        this.config = config;
        /** relative path -> { tests, tags } for the files this run actually collected. */
        this.ran = new Map();
        for (const test of suite.allTests()) {
            const file = relative(config.rootDir, test.location.file);
            let entry = this.ran.get(file);
            if (!entry) {
                entry = { tests: 0, tags: new Set() };
                this.ran.set(file, entry);
            }
            entry.tests += 1;
            for (const tag of test.tags) {
                if (BACKEND_TAGS.includes(tag)) entry.tags.add(tag);
            }
        }
    }

    onEnd() {
        const lines = [];
        const say = (line = "") => lines.push(line);

        const cli = readGrepArgs(process.argv);
        const patterns = cli.grep.length ? cli.grep : grepPatterns(this.config.grep).map((re) => re.source);
        const inverts = cli.invert.length ? cli.invert : grepPatterns(this.config.grepInvert).map((re) => re.source);
        const onDisk = findSpecFiles(this.config.rootDir).map((f) => relative(this.config.rootDir, f));

        const notRun = [];
        const undeclared = [];
        const disagreements = [];
        let ranTests = 0;

        for (const file of onDisk) {
            const run = this.ran.get(file);
            let parsed;
            try {
                parsed = parseDeclaredTags(readFileSync(join(this.config.rootDir, file), "utf8"));
            } catch {
                parsed = new Set();
            }

            if (run) {
                ranTests += run.tests;
                // The parser's self-check: Playwright's tags are authoritative here.
                if (sorted(parsed) !== sorted(run.tags)) {
                    disagreements.push(`${file}: declared ${sorted(run.tags) || "none"}, parser read ${sorted(parsed) || "none"}`);
                }
                if (run.tags.size === 0) undeclared.push(file);
                continue;
            }

            if (parsed.size === 0) {
                undeclared.push(file);
                notRun.push({ file, tags: "no backend tag", why: "undeclared — see below" });
            } else if (inverts.length && matchesAny(inverts, parsed)) {
                notRun.push({ file, tags: sorted(parsed), why: "excluded by the tag filter" });
            } else if (patterns.length && !matchesAny(patterns, parsed)) {
                notRun.push({ file, tags: sorted(parsed), why: "excluded by the tag filter" });
            } else {
                notRun.push({ file, tags: sorted(parsed), why: "not selected by this run's paths" });
            }
        }

        const filter = [
            ...patterns.map((p) => `--grep ${p}`),
            ...inverts.map((p) => `--grep-invert ${p}`),
        ].join(" ") || "none — no tag filter, so every declared backend is in scope";

        say();
        say("── Backend coverage (D16) ────────────────────────────────────────────────────");
        say(`   filter     ${filter}`);
        say(`   ran        ${this.ran.size} of ${onDisk.length} spec files, ${ranTests} test${ranTests === 1 ? "" : "s"}`);

        if (notRun.length === 0) {
            say(`   not run    none — every spec file on disk ran`);
        } else {
            const width = Math.max(...notRun.map((n) => n.file.length));
            say(`   NOT RUN    ${notRun.length} spec file${notRun.length === 1 ? "" : "s"} — not run, not passed:`);
            for (const { file, tags, why } of notRun) {
                say(`              ${file.padEnd(width)}  ${tags.padEnd(26)}  ${why}`);
            }
        }

        if (undeclared.length) {
            const one = undeclared.length === 1;
            say(`   UNDECLARED ${undeclared.length} spec file${one ? "" : "s"} declare${one ? "s" : ""} no backend tag, so no`);
            say(`              tag-filtered run will ever execute ${one ? "it" : "them"} (D16):`);
            for (const file of undeclared) say(`              ${file}`);
        } else {
            say(`   undeclared none — every spec file declares a backend`);
        }

        for (const line of disagreements) {
            say(`   PARSER     disagrees with Playwright on ${line}`);
        }

        say("──────────────────────────────────────────────────────────────────────────────");
        say();
        console.log(lines.join("\n"));
    }
}

export default BackendTagReporter;
